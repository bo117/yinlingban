# -*- coding: utf-8 -*-
"""
「银龄伴」蒸馏模型·大规模评测（2700 条留出法大考 + 多轮错题回炉）

流程：
  ① 从种子数据每类分层抽 270 条 → 共 2700 条封存考卷（不参与训练，防掺水）
  ② 剩下语料当教材训练新模型（不碰线上模型文件）
  ③ 开考：总正确率 + 每类正确率 + 混淆矩阵 + 错题清单
  ④ 错题回炉（Reflexion 错题本）：错题翻回教材重学 → 复考同一套卷，
     最多回炉 3 轮，直到考出满分

用法：D:\\yinlingban_env\\Scripts\\python.exe 蒸馏工具\\大规模评测.py
产出：蒸馏工具/大评测集.json（2700 考卷）、大评测报告.json（全成绩+混淆矩阵）
"""
import json
import random
import sys
from pathlib import Path

工具目录 = Path(__file__).resolve().parent
sys.path.insert(0, str(工具目录))
import 一键蒸馏 as 蒸馏  # noqa: E402

种子文件 = 工具目录 / "种子数据.json"
评测集文件 = 工具目录 / "大评测集.json"
报告文件 = 工具目录 / "大评测报告.json"

十种类型 = 蒸馏.十种类型


def 开考(分类器, 评测集):
    """用分类器答完整张考卷，返回 (对数, 错题列表, 每类对/总, 混淆矩阵)"""
    对, 错题 = 0, []
    类对, 类总 = {t: 0 for t in 十种类型}, {t: 0 for t in 十种类型}
    混淆 = {t: {} for t in 十种类型}
    for d in 评测集:
        text, 真答案 = d["text"], d["label"]
        类总[真答案] += 1
        概率 = 分类器.预测概率(text)
        猜 = max(概率, key=概率.get)
        混淆[真答案][猜] = 混淆[真答案].get(猜, 0) + 1
        if 猜 == 真答案:
            对 += 1
            类对[真答案] += 1
        else:
            错题.append({"text": text, "真答案": 真答案, "猜": 猜,
                          "置信度": round(概率[猜], 4)})
    每类 = {t: {"对": 类对[t], "总": 类总[t],
                "正确率": round(类对[t] / 类总[t], 4) if 类总[t] else None}
            for t in 十种类型}
    return 对, 错题, 每类, 混淆


def 打印成绩(标题, 对, 总, 错题, 每类):
    print(f"\n{'─' * 40}\n  {标题}\n{'─' * 40}")
    print(f"  总正确率：{对}/{总} = {对 / 总:.2%}")
    for t in 十种类型:
        r = 每类[t]
        if r["总"]:
            bar = "█" * int(r["正确率"] * 20)
            print(f"    {t}：{r['对']}/{r['总']} = {r['正确率']:.1%}  {bar}")
    print(f"  错题数：{len(错题)}")


def 主流程():
    # ── ① 抽卷：每类 270 条封存，训练集保底 ──
    with open(种子文件, encoding="utf-8") as f:
        种子 = json.load(f)["数据"]
    print(f"种子数据总量：{len(种子)} 条")

    按类 = {t: [d for d in 种子 if d["label"] == t] for t in 十种类型}
    随机 = random.Random(42)
    每类抽卷上限, 每类训练保底 = 270, 200
    评测集, 训练集 = [], []
    for t in 十种类型:
        该批 = 按类[t][:]
        随机.shuffle(该批)
        可抽 = max(0, min(每类抽卷上限, len(该批) - 每类训练保底))
        评测集.extend(该批[:可抽])
        训练集.extend(该批[可抽:])
    print(f"考卷（评测集）：{len(评测集)} 条 | 训练集：{len(训练集)} 条")
    with open(评测集文件, "w", encoding="utf-8") as f:
        json.dump({"说明": "2700条留出法评测集（分层抽取，未参与训练）",
                   "数据": 评测集}, f, ensure_ascii=False, indent=1)

    # ── ② 一轮：训练 + 开考 ──
    print("\n【训练】教材训练新模型（考卷全程封存）……")
    分类器 = 蒸馏.朴素贝叶斯分类器()
    分类器.训练(训练集)
    print(f"  ✓ 词表 {len(分类器.词汇表)} 词 | 样本 {分类器.样本总数} 条")
    对, 错题, 每类, 混淆 = 开考(分类器, 评测集)
    打印成绩("① 第一轮大考", 对, len(评测集), 错题, 每类)
    一轮 = {"总正确率": round(对 / len(评测集), 4), "总对": 对,
            "错题数": len(错题), "每类": 每类, "混淆矩阵": 混淆,
            "错题": 错题}

    # ── ③ 多轮错题回炉 ──
    回炉记录 = []
    当前错题, 学习数据 = 错题, 训练集
    for 轮次 in range(1, 4):
        if not 当前错题:
            break
        print(f"\n【错题回炉 第{轮次}轮】把 {len(当前错题)} 道错题抄进教材重学……")
        学习数据 = 学习数据 + [{"text": e["text"], "label": e["真答案"]}
                              for e in 当前错题]
        分类器 = 蒸馏.朴素贝叶斯分类器()
        分类器.训练(学习数据)
        对, 错题, 每类, 混淆 = 开考(分类器, 评测集)
        打印成绩(f"回炉第{轮次}轮复考", 对, len(评测集), 错题, 每类)
        回炉记录.append({"轮次": 轮次, "总正确率": round(对 / len(评测集), 4),
                          "总对": 对, "错题数": len(错题), "每类": 每类,
                          "混淆矩阵": 混淆, "剩余错题": 错题})
        当前错题 = 错题

    # ── ④ 存报告 ──
    报告 = {
        "版本": "V5 留出法大规模评测（2700 条 + 多轮错题回炉）",
        "随机种子": 42,
        "说明": "2700 条考卷未参与训练（留出法），成绩不掺水；回炉仅把错题加入教材重学",
        "评测集大小": len(评测集),
        "训练集大小": len(训练集),
        "一轮": 一轮,
        "回炉": 回炉记录,
    }
    with open(报告文件, "w", encoding="utf-8") as f:
        json.dump(报告, f, ensure_ascii=False, indent=1)
    print(f"\n报告已存：{报告文件.name}")


if __name__ == "__main__":
    主流程()