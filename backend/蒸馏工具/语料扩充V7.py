def main():
    print("=" * 60)
    print("  语料扩充 V7：机器增强批量造句")
    print("=" * 60)
    载 = json.loads(种子文件.read_text(encoding="utf-8"))
    旧 = 载["数据"]
    from collections import Counter
    旧分布 = Counter(x["label"] for x in 旧)
    print(f"  当前种子：{len(旧)} 条")

    seen = {(x["text"], x["label"]) for x in 旧}
    新增 = []
    rng = random.Random(20260911)

    # ── ① 同义替换增强 ──
    待增强 = [x for x in 旧 if len(x["text"]) >= 10]
    rng.shuffle(待增强)
    for x in 待增强[:len(待增强)]:
        if len(新增) >= 15000:
            break
        句 = x["text"]
        替换点 = []
        for 词, 替们 in 同义表.items():
            if 词 in 句:
                替换点.append((词, 替们))
        if not 替换点:
            continue
        # 每句最多生成 3 个变体，每次替换 1~3 处
        for _ in range(3):
            if len(新增) >= 15000:
                break
            新句 = 句
            用点 = rng.sample(替换点, min(len(替换点), rng.randint(1, 3)))
            for 词, 替们 in 用点:
                新句 = 新句.replace(词, rng.choice(替们), 1)
            if 新句 == 句 or len(新句) < 8:
                continue
            if (新句, x["label"]) not in seen:
                seen.add((新句, x["label"]))
                新增.append({"text": 新句, "label": x["label"]})

    # ── ② 边界自证句 ──
    for 类型, 句们 in 边界句.items():
        for 句 in 句们:
            if (句, 类型) not in seen:
                seen.add((句, 类型))
                新增.append({"text": 句, "label": 类型})

    全部 = 旧 + 新增
    种子文件.write_text(
        json.dumps({"说明": "「银龄伴」训练种子数据：十类 + V7 机器增强（2026-09-08）",
                    "数据": 全部}, ensure_ascii=False),
        encoding="utf-8")
    新分布 = Counter(x["label"] for x in 全部)
    print(f"  本批新增：{len(新增)} 条（同义替换 + 边界自证句）")
    print(f"  种子合计：{len(全部)} 条")
    print(f"  分布：{dict(新分布)}")
    print("\n  下一步：python 蒸馏工具\\一键蒸馏.py 重训")


if __name__ == "__main__":
    main()