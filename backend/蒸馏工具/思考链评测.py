def main():
    print("=" * 72)
    print(f"  思考链评测：{len(用例)} 个场景（意图识别 / 回复红线 / 置信度校准 / 诚实 / 转折感知）")
    print("=" * 72)

    逐条 = []
    for 名称, 参, 期望意图, 期望回复, (lo, hi) in 用例:
        r = 出(**参)
        reply = r["reply"]
        steps = r.get("thought_steps", [])
        conf = r.get("confidence", {})
        # 识别步文本
        认 = next((s["text"] for s in steps if s["n"] == 2), "")
        # ① 意图正确（越界题不校验具体意图名）
        ok_意 = (not 期望意图) or 期望意图 in 认
        # ② 回复红线达标
        ok_回 = any(w in reply for w in 期望回复)
        # 越界专项：必须出现"医生/大夫"等诚实话术
        if 期望意图 == "":
            ok_回 = ok_回 and ("医生" in reply or "大夫" in reply or "知识库" in reply)
        # ③ 置信度落点合规
        ok_信 = lo <= conf.get("score", -1) <= hi
        逐条.append((名称, ok_意, ok_回, ok_信, reply[:40], conf))

    # 打印明细
    print("-" * 72)
    print(f"  {'场景':<16} {'意图':<4} {'回复':<4} {'置信':<4}  回复预览")
    for 名称, oi, or_, oc, prev, conf in 逐条:
        print(f"  {名称:<16} {'✔' if oi else '✘':<4} {'✔' if or_ else '✘':<4} "
              f"{'✔' if oc else '✘':<4}  {prev}…")
    print("=" * 72)

    # ---------- 类型感知专项（V4：十类装进思考链） ----------
    print("  【类型感知专项】每种类型出现时，思考链『组织』步要说对口")
    ten = ["孤独型", "焦虑型", "开朗型", "低落型", "平静型",
           "急躁型", "唠叨型", "怀旧型", "依赖型", "勤俭型"]
    类型对 = 0
    for t in ten:
        r = 引擎.think_and_respond("我最近总觉得心里空落落的",
                                    user_name="张奶奶", profile_type=t)
        组织步 = next((s["text"] for s in r.get("thought_steps", [])
                      if s["n"] == 5), "")
        ok = t in 组织步
        类型对 += ok
        print(f"  {'✔' if ok else '✘'} {t} → 组织步含类型标签")
    打印率 = 类型对 / len(ten)
    print(f"  十类类型感知准确率：{类型对}/{len(ten)} = {打印率:.0%}")
    print("=" * 72)

    n = len(用例)
    意图总 = sum(1 for t in 逐条 if t[1])
    回复总 = sum(1 for t in 逐条 if t[2])
    置信总 = sum(1 for t in 逐条 if t[3])
    全过 = sum(1 for t in 逐条 if t[1] and t[2] and t[3])

    print("  【汇总】")
    print(f"  ① 意图识别准确率：{意图总}/{n} = {意图总 / n:.0%}")
    print(f"  ② 回复红线达标率：{回复总}/{n} = {回复总 / n:.0%}")
    print(f"  ③ 置信度校准合规：{置信总}/{n} = {置信总 / n:.0%}（有据才高置信，无据不装懂）")
    print(f"  ④ 全维度全对场景：{全过}/{n} = {全过 / n:.0%}")
    越界题集 = [t for t in 逐条 if "越界" in t[0]]
    if 越界题集:
        诚实 = sum(1 for t in 越界题集 if t[2] and t[5].get("level") == "低")
        print(f"  ⑤ 库外问题诚实拒答率：{诚实}/{len(越界题集)} = {诚实 / len(越界题集):.0%}"
              f"（都走'建议问医生'且置信度=低）")
    print("=" * 72)
    return 0 if 全过 == n else 1


if __name__ == "__main__":
    sys.exit(main())