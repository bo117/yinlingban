def main():
    print("=" * 56)
    print("  综合判定验证：模拟真实用户多题汇总判定")
    print("=" * 56)
    全对 = 0
    for 姓名, 数据 in 模拟用户.items():
        累加 = {}
        for ans in 数据["answers"]:
            概率 = m.predict(ans)
            for t, p in 概率.items():
                累加[t] = 累加.get(t, 0) + p
        判定 = max(累加, key=累加.get)
        正确 = 数据["true"] == 判定
        全对 += 正确
        print(f"  {'✓' if 正确 else '✗'} {姓名}：多题汇总判定 → {判定}（正确：{数据['true']}）")
        print(f"      汇总分布：{dict(sorted(累加.items(), key=lambda x: -x[1]))}")
    print(f"\n  综合判定准确率：{全对}/{len(模拟用户)}")
    print("=" * 56)


if __name__ == "__main__":
    main()