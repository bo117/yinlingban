    print(f"  答对：{对}/{总数} = {对 / 总数:.0%}")
    print(f"  各类判定分布：{dict(分布)}")
    if 分错:
        print(f"\n  答错的 {len(分错)} 句：")
        for 句子, 正确, 猜 in 分错:
            print(f"    ✗「{句子}」→ 判成{猜}（应为{正确}）")
    结论 = "优秀，能上线" if 对 / 总数 >= 0.85 else "可用，继续攒数据" if 对 / 总数 >= 0.7 else "需再训练"
    print(f"\n  结论：{结论}")

    # 错题落盘（Reflexion 错题本）：供 严格考试错题回炉.py 翻回教材重学
    if 分错:
        错题文件 = Path(__file__).resolve().parent / "严格考试错题.json"
        错题文件.write_text(json.dumps(
            {"总句数": 总数, "答对": 对, "正确率": round(对 / 总数, 4),
             "判定分布": dict(分布),
             "错题": [{"text": s, "真答案": z, "猜": g} for s, z, g in 分错]},
            ensure_ascii=False, indent=1), encoding="utf-8")
        print(f"  错题已存：{错题文件.name} → 跑「严格考试错题回炉.py」翻回教材重学")

    return 0 if 对 / 总数 >= 0.7 else 1


