def load_predict(model_dir: Path):
    spec = importlib.util.spec_from_file_location("m", model_dir / "predict.py")
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


def main():
    目录 = Path(sys.argv[1]) if len(sys.argv) > 1 else 工具目录 / "我的模型"
    print("=" * 66)
    print(f"  十类分型评测：{len(用例)} 题（含否定/隐含/长句 hard 题）")
    print(f"  模型：{目录}")
    print("=" * 66)
    模型 = load_predict(目录)
    对 = 0
    for 句, 期望 in 用例:
        r = 模型.predict(句)
        猜 = max(r, key=r.get)
        ok = 猜 == 期望
        对 += ok
        print(f"  {'✔' if ok else '✗'} 「{句}」→ {猜}（{r[猜]:.2f}）期望：{期望}")
    率 = 对 / len(用例)
    print("-" * 66)
    print(f"  总正确率：{对}/{len(用例)} = {率:.0%}")
    print("=" * 66)
    return 0 if 率 >= 0.9 else 1


if __name__ == "__main__":
    sys.exit(main())