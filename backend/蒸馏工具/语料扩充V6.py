def main():
    print("=" * 60)
    print("  语料扩充 V6：五个小类补齐到 1000 条/类")
    print("=" * 60)
    载 = json.loads(种子文件.read_text(encoding="utf-8"))
    旧 = 载["数据"]
    from collections import Counter
    旧分布 = Counter(x["label"] for x in 旧)
    print(f"  当前种子：{len(旧)} 条")

    seen = {(x["text"], x["label"]) for x in 旧}
    新增 = 0
    rng = random.Random(20260909)
    for 类型, (模板们, 变体们, 固定们) in 各类语料.items():
        当前 = 旧分布.get(类型, 0)
        条 = []
        for t in 模板们:
            组合 = list(itertools.product(变体们,))
            if len(组合) > 每模板上限:
                组合 = rng.sample(组合, 每模板上限)
            for (v,) in 组合:
                条.append(t.format(v))
        条.extend(固定们)
        新加 = 0
        for t in 条:
            if (t, 类型) not in seen:
                seen.add((t, 类型))
                旧.append({"text": t, "label": 类型})
                新加 += 1
        新增 += 新加
        print(f"    {类型}：{当前} → {当前 + 新加} 条（本批新增 {新加}）")

    种子文件.write_text(
        json.dumps({"说明": "「银龄伴」训练种子数据：十类 + V6 小类补齐（2026-09-08）",
                    "数据": 旧}, ensure_ascii=False),
        encoding="utf-8")
    终分布 = Counter(x["label"] for x in 旧)
    print(f"\n  本批新增：{新增} 条 | 种子合计：{len(旧)} 条")
    print(f"  最终分布：{dict(终分布)}")
    print("\n  下一步：python 蒸馏工具\\一键蒸馏.py 重训")


if __name__ == "__main__":
    main()