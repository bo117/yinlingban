def 提取特征(text: str) -> list:
    """
    提取文本特征（V5：五层特征）
    ① 二字短语 + 整词（原有）
    ② 语义信号（SIG:前缀，含蓄表达的强证据）
    ③ 转折感知（TURN:前缀）——读"转折复句"，转折后的半句才见真章
    ④ 否定感知（NEG:前缀）——"否定词+情绪"要反转，别把"我不难过"当难过
    ⑤ 判别式加权词由训练侧单独命中（DIS:前缀，见分类器.训练）
    """
    特征 = []
    # ① 词与短语特征
    tokens = 分词(text)
    特征.extend(tokens)

    # ③ 转折感知：切出转折词后面的子串，作为加权的"转折重点"特征
    转折词 = ["可照样", "可挡不住", "可还是", "可我不", "可我", "可我说", "可挡不",
             "但是", "可是", "然而", "其实", "照样", "却还", "却"]
    for 词 in 转折词:
        idx = text.find(词)
        if idx >= 0:
            后半 = text[idx + len(词):]
            if len(后半) >= 3:
                # 后半句的普通分词特征都打上 TURN: 前缀（重点强调）
                for t in 分词(后半):
                    特征.append(f"TURN:{t}")
                # 后半句的语义信号也算（转折后听真话）
                for 类型, 信号表 in 语义信号.items():
                    for 信号 in 信号表:
                        if 信号 in 后半:
                            特征.append(f"TURN:SIG:{类型}:1")
                break  # 取第一个转折点即可

    # ② 全句语义信号特征
    for 类型, 信号表 in 语义信号.items():
        命中 = 0
        for 信号 in 信号表:
            if 信号 in text:
                命中 += 1
        if 命中 > 0:
            特征.append(f"SIG:{类型}:{min(命中, 3)}")

    # ④ 否定感知：
    #    a) 否定词后面 ≤6 字窗口里的词 → 打 NEG: 前缀（"不+难过"整体成了独立特征）
    #    b) 句中同时有否定词和某类信号 → NEG:SIG:该类（模型学会"否定的信号"≠该信号）
    if any(n in text for n in 否定词表):
        for n in 否定词表:
            idx = text.find(n)
            if idx >= 0:
                窗口 = text[idx + len(n): idx + len(n) + 6]
                for t in 分词(窗口):
                    特征.append(f"NEG:{t}")
                break  # 取第一个否定点即可
        for 类型, 信号表 in 语义信号.items():
            for 信号 in 信号表:
                if 信号 in text:
                    特征.append(f"NEG:SIG:{类型}:1")
                    break
    return 特征


