# 第②步：训练（V2：TF-IDF 加权朴素贝叶斯 + 语义信号）
# ============================================================
class 朴素贝叶斯分类器:
    """
    V2 架构（治"模板句会、真实句不会"的泛化短板）：
      - TF-IDF 加权：常见词降权，区分度高的词升权
      - 语义信号特征：含蓄表达（"话外音"）作为强证据，权重放大
    """

    def __init__(self):
        self.词频 = defaultdict(Counter)      # 类型 → {特征: 次数}
        self.类计数 = Counter()
        self.总词数 = defaultdict(int)
        self.词汇表 = set()
        self.样本总数 = 0
        self.文档频率 = Counter()             # 特征出现在多少个样本（算IDF用）
        self.信号权重 = 3.0                    # 语义信号特征放大倍数
        self.转折权重 = 2.0                    # 转折重点特征放大倍数
        self.否定权重 = 1.6                    # V5：否定特征放大倍数
        self.判别词 = {}                      # V5：类型 → {区分词: 对数几率权重}
        self.判别权重 = 2.2                    # V5：判别词命中时的额外权重

    def _计算判别词(self, 类特征计数: dict, 类样本数: dict):
        """
        V5 判别式加权层（把朴素贝叶斯从"生成式"往"判别式"方向拉）：
        对每个普通词，看它"在该类样本里 vs 在其他类里"的出现对数几率，
        选每类 top 160 个最强的区分词。预测时只要命中就给该类加分——
        相当于给小模型一张"这个词到底是哪类人的"对照表。
        """
        self.判别词 = {}
        N = sum(类样本数.values())
        for 类型 in 十种类型:
            n = 类样本数.get(类型, 0)
            if n < 8:
                continue
            o = N - n
            打分 = []
            for f, a in 类特征计数.get(类型, {}).items():
                if f.startswith(("SIG:", "TURN:", "NEG:", "DIS:")):
                    continue  # 带前缀的强特征有专门的权重机制，不进判别表
                if a < 3:
                    continue
                b = sum(类特征计数.get(t, {}).get(f, 0) for t in 十种类型 if t != 类型)
                # log-odds：该词在类内出现的对数几率 - 在类外出现的对数几率
                w = math.log((a + 0.5) / (n - a + 0.5)) - math.log((b + 0.5) / (o - b + 0.5))
                if w > 0:
                    打分.append((w, f))
            打分.sort(reverse=True)
            self.判别词[类型] = {f: round(w, 4) for w, f in 打分[:160]}

    def 训练(self, 数据: list):
        # 第一遍：统计文档频率 + 逐类特征计数（算 IDF 和判别词用）
        样本特征 = []
        类特征计数 = defaultdict(Counter)
        类样本数 = Counter()
        for 条 in 数据:
            特征 = 提取特征(条["text"])
            样本特征.append((条, 特征))
            for f in set(特征):
                self.文档频率[f] += 1
            类 = 条["label"]
            类样本数[类] += 1
            for f in set(特征):
                if not f.startswith(("SIG:", "TURN:", "NEG:", "DIS:")):
                    类特征计数[类][f] += 1
        # 判别式加权词表（数据驱动：区分度高的词权重高）
        self._计算判别词(类特征计数, 类样本数)

        # 第二遍：按 TF-IDF 权重累计词频（训练/推理同一套加权规则）
        N = len(数据)
        for 条, 特征 in 样本特征:
            类型 = 条["label"]
            self.类计数[类型] += 1
            self.样本总数 += 1
            self.词汇表.update(特征)
            加权 = Counter()
            for f in 特征:
                idf = math.log((N + 1) / (self.文档频率.get(f, 0) + 1)) + 1.0
                加权[f] += idf
            # 语义信号放大 + 转折放大 + 否定放大
            for f in list(加权):
                if f.startswith("SIG:"):
                    加权[f] *= self.信号权重
                elif f.startswith("TURN:"):
                    加权[f] *= self.转折权重
                elif f.startswith("NEG:"):
                    加权[f] *= self.否定权重
            # 判别式加权：句子里出现某类的强区分词 → 给该类特征加额外分
            for 类, 词表 in self.判别词.items():
                for 词, 权 in 词表.items():
                    if 词 in 条["text"]:
                        加权[f"DIS:{类}:{词}"] += 权 * self.判别权重
            self.总词数[类型] += sum(加权.values())
            self.词频[类型].update(加权)

    def 预测概率(self, text: str) -> dict:
        """返回十类概率（V5：预测侧与训练侧完全一致的 TF-IDF + 信号/转折/否定放大 + 判别加权）"""
        特征 = 提取特征(text)
        词表大小 = max(len(self.词汇表), 1)
        # 预测侧的加权（与训练侧一致）
        N = self.样本总数
        加权 = Counter()
        for f in 特征:
            idf = math.log((N + 1) / (self.文档频率.get(f, 0) + 1)) + 1.0
            加权[f] += idf
        for f in list(加权):
            if f.startswith("SIG:"):
                加权[f] *= self.信号权重
            elif f.startswith("TURN:"):
                加权[f] *= self.转折权重
            elif f.startswith("NEG:"):
                加权[f] *= self.否定权重
        # 判别式加权（与训练侧一致）
        for 类, 词表 in self.判别词.items():
            for 词, 权 in 词表.items():
                if 词 in text:
                    加权[f"DIS:{类}:{词}"] += 权 * self.判别权重

        分数 = {}
        for 类型 in 十种类型:
            先验 = (self.类计数.get(类型, 0) + 1) / (self.样本总数 + len(十种类型))
            log分 = math.log(先验)
            该类词频 = self.词频[类型]
            该类总词 = self.总词数.get(类型, 0)
            for f, 权 in 加权.items():
                p = (该类词频.get(f, 0) + 0.5) / (该类总词 + 0.5 * 词表大小)
                log分 += 权 * math.log(p)
            分数[类型] = log分
        最高 = max(分数.values())
        exp分 = {t: math.exp(s - 最高) for t, s in 分数.items()}
        总和 = sum(exp分.values())
        return {t: round(v / 总和, 4) for t, v in exp分.items()}

    def 预测(self, text: str) -> str:
        概率 = self.预测概率(text)
        return max(概率, key=概率.get)

    def 保存(self, 目录: Path):
        """把模型存成 JSON（含语义信号表，推理器直接读）"""
        模型 = {
            "版本": "5.0",
            "说明": "「银龄伴」老人分型·蒸馏模型V5（十类：TF-IDF贝叶斯+语义信号+转折/否定感知+判别式加权）",
            "类型列表": 十种类型,
            "类计数": dict(self.类计数),
            "总词数": dict(self.总词数),
            "样本总数": self.样本总数,
            "词频": {t: dict(c) for t, c in self.词频.items()},
            "文档频率": dict(self.文档频率),
            "信号权重": self.信号权重,
            "转折权重": self.转折权重,
            "否定权重": self.否定权重,
            "判别权重": self.判别权重,
            "判别词": {t: dict(d) for t, d in self.判别词.items()},
            "语义信号": 语义信号,
        }
        目录.mkdir(parents=True, exist_ok=True)
        (目录 / "模型.json").write_text(
            json.dumps(模型, ensure_ascii=False), encoding="utf-8")

    @classmethod
    def 加载(cls, 目录: Path):
        obj = cls()
        模型 = json.loads((目录 / "模型.json").read_text(encoding="utf-8"))
        obj.类计数 = Counter(模型["类计数"])
        obj.总词数 = defaultdict(int, 模型["总词数"])
        obj.样本总数 = 模型["样本总数"]
        obj.文档频率 = Counter(模型.get("文档频率", {}))
        obj.词汇表 = set()
        obj.词频 = defaultdict(Counter)
        for t, c in 模型["词频"].items():
            obj.词频[t] = Counter(c)
            obj.词汇表.update(c.keys())
        obj.否定权重 = 模型.get("否定权重", 1.6)
        obj.判别权重 = 模型.get("判别权重", 2.2)
        obj.判别词 = {t: dict(d) for t, d in 模型.get("判别词", {}).items()}
        return obj


