# ============================================================
# 第①步：导出真实聊天数据（从数据库里捞）
# ============================================================
def 导出真实数据() -> list:
    """
    从数据库导出真实训练数据：
      - 引导问答记录（onboarding_answers 表）：每条回答 + 该老人的最终类型
      - 分型完成的用户消息（messages 表）：带类型的用户话
    返回 [{"text": ..., "label": ...}, ...]
    """
    真实数据 = []
    if not 数据库文件.exists():
        print("  （还没聊天记录，跳过导出——只用种子数据训练）")
        return 真实数据

    try:
        import sqlite3
        conn = sqlite3.connect(str(数据库文件))
        conn.row_factory = sqlite3.Row
        cur = conn.cursor()

        # 方式一：引导问答 → 每条回答都带上老人的最终分型标签
        # （这才是"点石成金"：规则打的标签反过来喂给模型，模型学会更聪明的判断）
        try:
            rows = cur.execute("""
                SELECT o.answer_text AS text, u.profile_type AS label
                FROM onboarding_answers o
                JOIN users u ON u.id = o.user_id
                WHERE u.profile_type != '' AND o.answer_text != ''
            """).fetchall()
            for r in rows:
                t = (r["text"] or "").strip()
                if t and r["label"] in 十种类型 and len(t) >= 4:
                    真实数据.append({"text": t, "label": r["label"]})
        except Exception:
            pass  # 表不存在（老库）就跳过

        # 方式二：分型完成的用户的普通聊天消息（每条都算该类型的样本）
        try:
            rows = cur.execute("""
                SELECT m.content AS text, u.profile_type AS label
                FROM messages m
                JOIN sessions s ON s.id = m.session_id
                JOIN users u ON u.id = s.user_id
                WHERE m.role = 'user' AND u.profile_type != ''
                  AND length(m.content) >= 6 AND length(m.content) <= 200
            """).fetchall()
            for r in rows:
                t = (r["text"] or "").strip()
                if t and r["label"] in 十种类型:
                    真实数据.append({"text": t, "label": r["label"]})
        except Exception:
            pass

        conn.close()
    except Exception as e:
        print(f"  （读数据库出错：{e}，只用种子数据训练）")

    return 真实数据


