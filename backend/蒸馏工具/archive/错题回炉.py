def main():
    print("=" * 56)
    print("  错题回炉：真实语料入库 + 含蓄变体扩充")
    print("=" * 56)

    原始 = json.loads(种子文件.read_text(encoding="utf-8"))
    现有 = 原始["数据"]
    已有文本 = {d["text"] for d in 现有}
    print(f"现有数据：{len(现有)} 条")

    # ① 真实语料入库
    加入 = 0
    for 句子, 标签 in 真实语料:
        if 句子 not in 已有文本:
            现有.append({"text": 句子, "label": 标签})
            已有文本.add(句子)
            加入 += 1
    print(f"① 真实语料新增：{加入} 条（错题本机制）")

    # ② 含蓄变体（每条配一个标签）
    变体数 = 0
    for 标签, 句组 in 改写规则.items():
        for 句 in 句组:
            if 句 not in 已有文本:
                现有.append({"text": 句, "label": 标签})
                已有文本.add(句)
                变体数 += 1
    print(f"② 含蓄变体新增：{变体数} 条")

    # 统计
    随机.shuffle(现有)
    分布 = Counter(d["label"] for d in 现有)
    print(f"合计：{len(现有)} 条")
    for t, n in sorted(分布.items()):
        print(f"    {t}：{n} 条")

    种子文件.write_text(json.dumps({
        "说明": "「银龄伴」老人分型·蒸馏训练数据（手工种子+模板扩充+真实语料回炉，共"
                + str(len(现有)) + "条）。由「一键蒸馏.py」自动加载训练。",
        "数据": 现有,
    }, ensure_ascii=False, indent=0), encoding="utf-8")
    print(f"\n✓ 已写入：{种子文件}")
    print("  下一步：运行 一键蒸馏.py 重新训练，再用 严格考试.py 换新题验证")


if __name__ == "__main__":
    main()
