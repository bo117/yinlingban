def main():
    原始 = json.loads(种子文件.read_text(encoding="utf-8"))
    现有 = 原始["数据"]
    已有 = {d["text"] for d in 现有}
    加 = 0
    for 句, 标签 in 回炉:
        if 句 not in 已有:
            现有.append({"text": 句, "label": 标签})
            加 += 1
    print(f"回炉新增：{加} 条（三考37句边界题）")
    print(f"数据总量：{len(现有)} 条")
    种子文件.write_text(json.dumps({
        "说明": "「银龄伴」老人分型·蒸馏训练数据（手工+模板+真实语料+边界题回炉，共"
                + str(len(现有)) + "条）。",
        "数据": 现有,
    }, ensure_ascii=False, indent=0), encoding="utf-8")
    print("✓ 已回炉。运行 一键蒸馏.py 重训")


if __name__ == "__main__":
    main()