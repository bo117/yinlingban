def main():
    对 = 0
    分错 = []
    分布 = Counter()
    for 句子, 正确 in 考题:
        概率 = m.predict(句子)
        猜 = max(概率, key=概率.get)
        分布[猜] += 1
        if 猜 == 正确:
            对 += 1
        else:
            分错.append((句子, 正确, 猜))

    总数 = len(考题)
    print("=" * 56)
    print(f"  五轮考试：{总数} 句全新变体（5类各8句）")
    print("=" * 56)
    print(f"  答对：{对}/{总数} = {对 / 总数:.0%}")
    if 分错:
        print(f"\n  错题：")
        for 句子, 正确, 猜 in 分错:
            print(f"    ✗「{句子}」→ {猜}（应为{正确}）")
    print(f"\n  成绩线：模板100% | 二考95% | 三考59%→回炉 | 四考65%→回炉 | 五考{对 / 总数:.0%}")
    return 0


if __name__ == "__main__":
    sys.exit(main())