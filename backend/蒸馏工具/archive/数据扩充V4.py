def _展开(模板们, 变体们, 每模板上限=每模板上限, 每类上限=150, seed=20260828):
    """模板里有 {0} 的 × 每个变体生成一句；没有槽位的原样收录"""
    rng = random.Random(seed)
    out = []
    for t in 模板们:
        if "{" in t:
            组合 = list(itertools.product(变体们,))
            if len(组合) > 每模板上限:
                组合 = rng.sample(组合, 每模板上限)
            for (v,) in 组合:
                out.append(t.format(v))
        else:
            out.append(t)
    return rng.sample(out, min(len(out), 每类上限)) if len(out) > 每类上限 else out


