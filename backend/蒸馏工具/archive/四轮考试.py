def main():
    对 = 0
    分错 = []
    分布 = Counter()
    for 句子, 正确 in 考题:
        概率 = m.predict(句子)
        猜 = max(概率, key=概率.get)
        分布[猜] += 1
        if 猜 == 正确:
            对 += 1
        else:
            分错.append((句子, 正确, 猜))

    总数 = len(考题)
    print("=" * 56)
    print(f"  四轮考试：{总数} 句全新变体（不回炉，考真泛化）")
