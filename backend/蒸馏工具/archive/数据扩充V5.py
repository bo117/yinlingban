# -*- coding: utf-8 -*-
"""
「银龄伴」数据扩充 · V5（否定/反差句专项）

【为什么】
论文验证：朴素贝叶斯把 "我不难过" 拆成 "我/不难过" 各算各的，容易判反。
老人说话恰恰爱用否定："我不难过""没什么好担心的""一点也不孤单"。
这版给种子数据补一批"否定句 + 正确标签"，让 V5 模型真见过这类话。

用法（会往 种子数据.json 追加，之后重跑 一键蒸馏.py）：
    D:\\yinlingban_env\\Scripts\\python.exe 蒸馏工具\\数据扩充V5.py
"""
import json
from pathlib import Path

工具目录 = Path(__file__).resolve().parent
种子文件 = 工具目录 / "种子数据.json"

# (句模板{0}, 标签)
否定样本 = [
    # ---- 低落→平静 ----
    ("其实我{0}", "平静型"),
    ("我{0}", "平静型"),
]
否定_低落词 = [
    "一点也不难过", "没觉得那么糟", "不再低落了", "不怎么难过了",
    "不觉得没意思了", "没那悲观了", "想开些了，不钻牛角尖了",
    "没心思再去难过", "不想那些伤心事了",
]
否定_焦虑词 = [
    "没什么好担心的了", "不担心了", "没那么多操心的了", "不愁了",
    "想开了，不愁那些了", "不焦虑了", "没什么可害怕的", "心里不慌了",
    "不悬着心了", "不再胡思乱想了",
]
否定_孤独词 = [
    "一点也不孤单", "不觉得孤单了", "有人陪着，不孤独了", "不冷清了",
    "怎么还会孤单呢", "不是没人陪", "没那么寂寞了",
]
否定_悲观 = [
    "说什么想不开呢，我看得开", "哪有什么过不去的", "愁也愁不来，不想了",
    "不是天天唉声叹气的，我现在挺好的", "没那心思想这想那了",
    "不那么想了，一天一天过得挺稳当",
]
开朗_样本 = [
    "我一点也不孤单，天天有人串门", "不是没人陪，老伙计多着呢",
    "一点都不觉得冷清，日子滋润", "哪会寂寞，忙都忙不过来",
    "现在有人陪着，心里别提多亮堂",
    "看开了，愁什么，吃嘛嘛香",
    "没什么可担心的，好日子在后头",
]


def main():
    print("=" * 60)
    print("  数据扩充 V5：否定/反差句专项")
    print("=" * 60)

    旧 = json.loads(种子文件.read_text(encoding="utf-8"))["数据"]
    print(f"  当前种子：{len(旧)} 条")

    新 = []
    # 低落否定
    for t in 否定_低落词:
        新.append({"text": "其实我" + t, "label": "平静型"})
    # 焦虑否定
    for t in 否定_焦虑词:
        新.append({"text": t + "了", "label": "平静型"})
    # 孤独否定
    for t in 否定_孤独词:
        新.append({"text": "我" + t, "label": "开朗型"})
    # 综合否定/看开
    for t in 否定_悲观:
        新.append({"text": t, "label": "平静型"})
    # 开朗肯定化
    for t in 开朗_样本:
        新.append({"text": t, "label": "开朗型"})

    # 去重合并
    seen = {(x["text"], x["label"]) for x in 旧}
    加 = [x for x in 新 if (x["text"], x["label"]) not in seen]
    全部 = 旧 + 加
    from collections import Counter
    分布 = Counter(x["label"] for x in 全部)

    种子文件.write_text(
        json.dumps({"说明": "「银龄伴」训练种子数据 V5：十类 + 否定/反差句",
                    "数据": 全部}, ensure_ascii=False),
        encoding="utf-8")
    print(f"  新增否定样本：{len(加)} 条")
    print(f"  合计：{len(全部)} 条")
    print(f"  分布：{dict(分布)}")
    print("\n  下一步：运行 一键蒸馏.py 重训 V5（含否定感知算法）")


if __name__ == "__main__":
    main()