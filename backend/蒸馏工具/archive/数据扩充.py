def 造句(模板: str, 素材: dict) -> str:
    """把模板的{槽位}随机填上素材"""
    result = 模板
    # 找出所有槽位名（可能重复出现，逐个填不同的值）
    import re
    slots = re.findall(r"\{(.+?)\}", 模板)
    for slot in set(slots):
        result = result.replace("{" + slot + "}", 随机.choice(素材[slot]))
    return result


def 扩充数据(已有数据: list) -> list:
    """补足到目标总数：缺哪类补哪类（在已有数据基础上增量生成）"""
    from collections import Counter
    已有 = Counter(d["label"] for d in 已有数据)

    类配置 = [
        ("孤独型", 孤独模板, 孤独),
        ("焦虑型", 焦虑模板, 焦虑),
        ("开朗型", 开朗模板, 开朗),
        ("低落型", 低落模板, 低落),
        ("平静型", 平静模板, 平静),
    ]
    新增 = []
    已见 = set(d["text"] for d in 已有数据)

    for 标签, 模板组, 素材 in 类配置:
        缺口 = 目标总数 // len(类配置) - 已有.get(标签, 0)
        if 缺口 <= 0:
            continue
        造了 = 0
        尝试 = 0
        while 造了 < 缺口 and 尝试 < 缺口 * 60:
            尝试 += 1
            句 = 造句(随机.choice(模板组), 素材)
            if 句 in 已见 or len(句) < 6:
                continue
            已见.add(句)
            新增.append({"text": 句, "label": 标签})
            造了 += 1
    return 新增


