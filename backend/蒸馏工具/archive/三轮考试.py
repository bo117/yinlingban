    ("对门热热闹闹，我这屋里头安安静静", "孤独型"),

    # 焦虑+低落（身体担心叠加无望）→ 焦虑（健康原因）
    ("这胃疼了三个月，怕是熬不过去了", "焦虑型"),
    ("血压高得吓人，我这心里发慌，怕是早晚出事", "焦虑型"),
    ("最近记性差得厉害，我怀疑是不是得了什么大病", "焦虑型"),
    ("心口闷得慌，越想越怕，觉都睡不好", "焦虑型"),

    # 开朗+焦虑共存（身体好但心态畅快为主语）→ 开朗
